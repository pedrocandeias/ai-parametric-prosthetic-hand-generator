FIELDS = [
    "source_document","source_page","source_citation",
    "measurement_name","body_region",
    "population","country","sex","sample_size",
    "stat_type","percentile",
    "value_cm","value_mm","value_in",
    "data_quality_note",
]

def cm_to_mm(v): return round(v * 10, 2)
def cm_to_in(v): return round(v / 2.54, 3)

def make_rows(m):
    rows = []
    note = m.get("notes", "")
    for sex_key, sex_label, n in [("female","female",FEMALE_N),("male","male",MALE_N)]:
        d = m[sex_key]
        sex_note = d.get("notes", note)  # per-sex note overrides if present
        base = {
            "source_document": SOURCE_DOC,
            "source_page": m["page"],
            "source_citation": CITATION,
            "measurement_name": m["name"],
            "body_region": m["body_region"],
            "population": POPULATION,
            "country": COUNTRY,
            "sex": sex_label,
            "sample_size": n,
            "data_quality_note": sex_note,
        }
        for stat in ("mean","std_dev","max","min"):
            if stat in d:
                rows.append({**base,
                    "stat_type": stat, "percentile": "",
                    "value_cm": d[stat],
                    "value_mm": cm_to_mm(d[stat]),
                    "value_in": cm_to_in(d[stat]),
                })
        for p, v in sorted(d["p"].items()):
            rows.append({**base,
                "stat_type": "percentile", "percentile": p,
                "value_cm": v,
                "value_mm": cm_to_mm(v),
                "value_in": cm_to_in(v),
            })
    return rows

def write_csv(path, rows):
    pathlib.Path(path).parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=FIELDS)
        w.writeheader()
        w.writerows(rows)
    print(f"Written {len(rows):,} rows → {path}")

if __name__ == "__main__":
    all_rows = []
